/**
 * Sync Aggregates
 * 同步模块聚合根导出
 * 
 * 【规范说明：聚合根（Aggregate Root）】
 * 聚合根是 DDD 中的核心概念：
 * - 聚合的入口点：外部只能通过聚合根访问聚合内的实体
 * - 事务边界：一次事务只能修改一个聚合根
 * - 不变量守护者：确保聚合内的业务规则始终满足
 * - 领域事件发布者：状态变更时发出领域事件
 * 
 * 【SyncSession 聚合根】
 * - 同步会话管理：每一次同步会话是一个聊天型的事务程序
 * - 冲突管理：检测、记录、解决冲突
 * - 版本控制：使用版本校验不一致的数据
 * 
 * 【SyncProfile 聚合根】
 * - 用户同步配置管理：每个用户的同步设置
 * - 设备信息管理：不同设备的设备信息（MD5, Agent等）
 * - 增量同步帏控：批次同步伊始化、位移更新控制
 */

